#[derive(Debug, Clone, Serialize, Deserialize, Default)]
#[serde(rename_all = "camelCase")]
pub struct BatchOperation {
    pub name: String,
    #[serde(default)]
    pub done: bool,
    pub metadata: Option<Value>,
    pub response: Option<Value>,
    pub error: Option<OperationStatus>,
}

impl BatchOperation {
    pub fn batch(&self) -> Option<Batch> {
        fn parse_batch(value: &Value) -> Option<Batch> {
            if let Ok(batch) = serde_json::from_value::<Batch>(value.clone()) {
                return Some(batch);
            }

            value
                .get("batch")
                .and_then(|inner| serde_json::from_value::<Batch>(inner.clone()).ok())
        }

        self.response
            .as_ref()
            .and_then(parse_batch)
            .or_else(|| self.metadata.as_ref().and_then(parse_batch))
    }

    pub fn batch_state(&self) -> Option<BatchState> {
        self.batch().and_then(|batch| batch.state)
    }

    pub fn is_terminal(&self) -> bool {
        if self.done {
            return true;
        }

        self.batch_state().is_some_and(|state| state.is_terminal())
    }
}

