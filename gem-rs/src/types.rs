impl File {
    pub(crate) async fn new(
        file_name: &str,
        bytes: Vec<u8>,
        mime_type: &str,
        api_key: &str,
        timeout: Option<Duration>,
        base_url: &str,
    ) -> Result<Self, GemError> {
        Self::upload(file_name, bytes, mime_type, api_key, timeout, base_url).await
    }

    async fn upload(
        file_name: &str,
        buffer: Vec<u8>,
        mime_type: &str,
        api_key: &str,
        timeout: Option<Duration>,
        base_url: &str,
    ) -> Result<Self, GemError> {
        let num_bytes = buffer.len();

        let mut client_builder = reqwest::Client::builder();
        if let Some(t) = timeout {
            client_builder = client_builder.timeout(t);
        } else {
            client_builder = client_builder.timeout(Duration::from_secs(300));
        }
        let client = client_builder.build().unwrap_or(reqwest::Client::new());

        let upload_url = format!("{}/upload/v1beta/files", base_url);

        let reserve_response = match client
            .post(upload_url)
            .query(&[("key", api_key)])
            .header("X-Goog-Upload-Protocol", "resumable")
            .header("X-Goog-Upload-Command", "start")
            .header("X-Goog-Upload-Header-Content-Length", num_bytes.to_string())
            .header("X-Goog-Upload-Header-Content-Type", mime_type)
            .header(header::CONTENT_TYPE, "application/json")
            .json(&json!({
                "file": { "display_name": file_name }
            }))
            .send()
            .await
        {
            Ok(response) => response,
            Err(e) => return Err(GemError::FileError(e.to_string())),
        };

        if !reserve_response.status().is_success() {
            let error_text = reserve_response.text().await.unwrap_or_default();
            return Err(GemError::FileError(format!(
                "Failed to start upload: {}",
                error_text
            )));
        }

        let location = match reserve_response.headers().get("X-Goog-Upload-URL") {
            Some(loc) => match loc.to_str() {
                Ok(l) => l,
                Err(e) => return Err(GemError::FileError(e.to_string())),
            },
            None => {
                return Err(GemError::FileError(
                    "X-Goog-Upload-URL header not found".to_string(),
                ))
            }
        };

        let upload_response = match client
            .put(location)
            .header("Content-Length", num_bytes.to_string())
            .header("X-Goog-Upload-Offset", "0")
            .header("X-Goog-Upload-Command", "upload, finalize")
            .body(buffer)
            .send()
            .await
        {
            Ok(response) => response,
            Err(e) => return Err(GemError::FileError(e.to_string())),
        };

        if !upload_response.status().is_success() {
            let error_text = upload_response.text().await.unwrap_or_default();
            return Err(GemError::FileError(format!(
                "Failed to upload bytes: {}",
                error_text
            )));
        }

        let upload_text_response = match upload_response.text().await {
            Ok(t) => t,
            Err(e) => return Err(GemError::FileError(e.to_string())),
        };

        let mut file: File = match serde_json::from_str::<Value>(&upload_text_response) {
            Ok(data) => match data.get("file") {
                Some(f) => match serde_json::from_value(f.clone()) {
                    Ok(file) => file,
                    Err(e) => {
                        log::error!("File error [0]: {} - Response: {}", e, upload_text_response);
                        return Err(GemError::FileError(e.to_string()));
                    }
                },
                None => {
                    return Err(GemError::FileError(
                        "File data not found in response".to_string(),
                    ))
                }
            },
            Err(e) => {
                log::error!("File error [1]: {} - Response: {}", e, upload_text_response);
                return Err(GemError::FileError(e.to_string()));
            }
        };

        let start_time = Instant::now();
        let time_limit = timeout.unwrap_or(Duration::from_secs(600));
        loop {
            if start_time.elapsed() > time_limit {
                return Err(GemError::FileError(format!(
                    "File processing timeout after {:?}",
                    time_limit
                )));
            }

            let file_state_response = match client
                .get(&format!("{}/v1beta/{}", base_url, file.name))
                .query(&[("key", api_key)])
                .send()
                .await
            {
                Ok(response) => response,
                Err(e) => return Err(GemError::FileError(e.to_string())),
            };

            let file_state_text = match file_state_response.text().await {
                Ok(t) => t,
                Err(e) => return Err(GemError::FileError(e.to_string())),
            };

            let file_state: File = match serde_json::from_str::<File>(&file_state_text) {
                Ok(f) => f,
                Err(e) => {
                    log::error!("File error [3]: {:#?}, response: {:#?}", e, file_state_text);
                    return Err(GemError::FileError(
                        "Failed to parse file state".to_string(),
                    ));
                }
            };

            if file_state.state == "ACTIVE" {
                break;
            } else if file_state.state == "FAILED" {
                return Err(GemError::FileError(
                    file_state
                        .error
                        .clone()
                        .unwrap_or(Status {
                            code: 0,
                            message: "File processing failed".to_string(),
                        })
                        .message,
                ));
            } else if file_state.state != "PROCESSING" {
                log::warn!("Unknown file state: {}", file_state.state);
                return Err(GemError::FileError(format!(
                    "File processing unknown state: {}",
                    file_state.state
                )));
            }

            tokio::time::sleep(Duration::from_secs(3)).await;
        }

        file.api_key = api_key.to_string();
        Ok(file)
    }

    async fn delete(self) -> Result<(), GemError> {
        log::info!("Deleting file: {:#?}", self);
        if self.api_key == "" {
            log::info!("API key not found: {:#?}", self.display_name);
            return Err(GemError::FileError("API key not found".to_string()));
        }
        let client = reqwest::Client::new();
        match client
            .delete(self.uri)
            .query(&[("key", self.api_key.clone())])
            .send()
            .await
        {
            Ok(_) => {
                log::info!("File deleted successfully: {:#?}", self.display_name);
                Ok(())
            }
            Err(e) => Err(GemError::FileError(e.to_string())),
        }
    }
}

#[derive(Debug)]
pub struct FileManager {
    files: Mutex<HashMap<String, File>>,
    api_key: String,
    base_url: String,
}

impl FileManager {
    pub fn new() -> Self {
        dotenv().ok();
        let api_key = std::env::var("GEMINI_API_KEY").expect("Failed to load Gemini API key");

        Self {
            files: Mutex::new(HashMap::new()),
            api_key: api_key.to_string(),
            base_url: DEFAULT_BASE_URL.to_string(),
        }
    }

    pub fn set_base_url(&mut self, url: &str) {
        self.base_url = url.trim_end_matches('/').to_string();
    }

    pub async fn download_file_bytes(&self, file_name: &str) -> Result<Vec<u8>, GemError> {
        let normalized = if file_name.starts_with("files/") {
            file_name.to_string()
        } else {
            format!("files/{}", file_name.trim_start_matches('/'))
        };

        let url = format!("{}/v1beta/{}:download", self.base_url, normalized);
        let client = reqwest::Client::new();
        let response = client
            .get(url)
            .query(&[("key", self.api_key.clone()), ("alt", "media".to_string())])
            .send()
            .await
            .map_err(|err| GemError::FileError(err.to_string()))?;

        if !response.status().is_success() {
            let body = response.text().await.unwrap_or_default();
            return Err(GemError::FileError(format!(
                "Failed to download file content: {}",
                body
            )));
        }

        response
            .bytes()
            .await
            .map(|bytes| bytes.to_vec())
            .map_err(|err| GemError::FileError(err.to_string()))
    }

    pub async fn download_file_string(&self, file_name: &str) -> Result<String, GemError> {
        let bytes = self.download_file_bytes(file_name).await?;
        String::from_utf8(bytes).map_err(|err| GemError::FileError(err.to_string()))
    }

    pub async fn add_file_from_bytes(
        &self,
        file_name: &str,
        bytes: Vec<u8>,
        mime_type: &str,
        timeout: Option<Duration>,
    ) -> Result<FileData, GemError> {
        let hash = sha256::digest(&bytes);
        match self.get_file(&hash).await {
            Some(file) => Ok(file),
            None => {
                let file = File::new(
                    file_name,
                    bytes,
                    mime_type,
                    &self.api_key,
                    timeout,
                    &self.base_url,
                )
                .await?;
                let mime_type = file.mime_type.clone();
                let file_uri = file.uri.clone();
                let uploaded_name = file.name.clone();
                let mut files = self.files.lock().await;
                files.insert(hash, file);
                Ok(FileData {
                    mime_type,
                    file_uri,
                    file_name: Some(uploaded_name),
                })
            }
        }
    }

    pub async fn add_file(
        &mut self,
        file_path: &Path,
        timeout: Option<Duration>,
    ) -> Result<FileData, GemError> {
        if !file_path.exists() {
            return Err(GemError::FileError("File does not exist".to_string()));
        }

        let file_name = match file_path.file_name() {
            Some(name) if name.to_str().is_some() => name.to_str().unwrap(),
            _ => return Err(GemError::FileError("Invalid file name".to_string())),
        };

        let mut file = match std::fs::File::open(file_path) {
            Ok(f) => f,
            Err(e) => return Err(GemError::FileError(e.to_string())),
        };

        let mut buffer = Vec::new();
        match std::io::Read::read_to_end(&mut file, &mut buffer) {
            Ok(_) => (),
            Err(e) => return Err(GemError::FileError(e.to_string())),
        };

        let mime_type = match get_mime_type(file_path) {
            Some(ext) => ext,
            None => return Err(GemError::FileError("Unsupported file type".to_string())),
        };

        let hash = sha256::digest(&buffer);

        match self.get_file(&hash).await {
            Some(file) => Ok(file),
            None => {
                let file = File::new(
                    file_name,
                    buffer,
                    &mime_type,
                    &self.api_key,
                    timeout,
                    &self.base_url,
                )
                .await?;
                let mime_type = file.mime_type.clone();
                let file_uri = file.uri.clone();
                let uploaded_name = file.name.clone();
                let mut files = self.files.lock().await;
                files.insert(hash, file);
                Ok(FileData {
                    mime_type,
                    file_uri,
                    file_name: Some(uploaded_name),
                })
            }
        }
    }

    pub async fn check_file(&self, hash: &str) -> bool {
        let files = self.files.lock().await;
        for file in files.iter() {
            if file.0 == hash {
                return true;
            }
        }
        false
    }

    pub async fn get_file(&self, hash: &str) -> Option<FileData> {
        let mut to_remove = Vec::new();
        let mut files = self.files.lock().await;
        for file in files.iter() {
            match file.0 == hash {
                true if file.1.expiration_time
                    > (chrono::Utc::now() + chrono::Duration::minutes(10)).to_rfc3339() =>
                {
                    log::info!("Found cached File: {:#?}", file.1);
                    return Some(FileData {
                        mime_type: file.1.mime_type.clone(),
                        file_uri: file.1.uri.clone(),
                        file_name: Some(file.1.name.clone()),
                    });
                }
                true => {
                    to_remove.push(file.0.clone());
                }
                false => continue,
            }
        }

        for hash in to_remove {
            let file = files.remove(&hash);
            if let Some(file) = file {
                let _ = file.delete().await;
            }
        }

        None
    }

    pub async fn fetch_list(&mut self) -> Result<HashMap<String, File>, GemError> {
        let client = reqwest::Client::new();
        let mut files = Vec::new();
        let mut page_token: Option<String> = None;

        loop {
            let mut request = client.get(format!("{}/v1beta/files", self.base_url));

            if let Some(token) = &page_token {
                request = request.query(&[("pageToken", token), ("key", &self.api_key)]);
            } else {
                request = request.query(&[("key", &self.api_key)]);
            }

            let response = match request.send().await {
                Ok(response) => response,
                Err(e) => return Err(GemError::FileError(e.to_string())),
            };

            let response_text = match response.text().await {
                Ok(data) => data,
                Err(e) => return Err(GemError::FileError(e.to_string())),
            };

            let response_json: Value = match serde_json::from_str(&response_text) {
                Ok(data) => data,
                Err(e) => {
                    log::error!("File error [6]: {}, response: {}", e, response_text);
                    return Err(GemError::FileError(e.to_string()));
                }
            };

            match response_json.get("files") {
                Some(f) => match serde_json::from_value::<Vec<File>>(f.clone()) {
                    Ok(mut new_files) => files.append(&mut new_files),
                    Err(e) => {
                        log::error!("File error [7]: {}, response: {}", e, response_text);
                        return Err(GemError::FileError(e.to_string()));
                    }
                },
                None => {
                    break;
                }
            };

            page_token = response_json
                .get("nextPageToken")
                .and_then(|t| t.as_str().map(String::from));
            if page_token.is_none() {
                break;
            }
        }

        let mut files_map = self.files.lock().await;
        let mut files_map_clone = HashMap::new();
        for file in files_map.iter() {
            files_map_clone.insert(file.0.clone(), file.1.clone());
        }

        for mut file in files {
            file.api_key = self.api_key.clone();
            log::info!("File: {:#?}", file);
            files_map.insert(file.sha256_hash.clone(), file.clone());
            files_map_clone.insert(file.sha256_hash.clone(), file);
        }

        Ok(files_map_clone)
    }

    pub async fn delete_file(&mut self, hash: &str) -> Result<(), GemError> {
        let mut files = self.files.lock().await;
        let file = files.remove(hash);
        match file {
            Some(file) => file.delete().await,
            None => Ok(()),
        }
    }

    pub async fn clear_files(&mut self) {
        let mut files = self.files.lock().await;
        let keys: Vec<String> = files.keys().cloned().collect();
        for key in keys {
            if let Some(file) = files.remove(&key) {
                let _ = file.delete().await;
            }
        }
    }
}

