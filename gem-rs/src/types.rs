pub fn parse_batch_jsonl_lines(content: &str) -> Result<Vec<BatchJsonlLine>, GemError> {
    let mut lines = Vec::new();
    for line in content.lines() {
        if line.trim().is_empty() {
            continue;
        }
        let parsed = serde_json::from_str::<BatchJsonlLine>(line)
            .map_err(|err| GemError::FileError(format!("Failed to parse JSONL line: {}", err)))?;
        lines.push(parsed);
    }
    Ok(lines)
}

pub fn group_batch_jsonl_by_key(
    lines: Vec<BatchJsonlLine>,
) -> BTreeMap<String, Vec<BatchJsonlLine>> {
    let mut grouped = BTreeMap::new();
    for line in lines {
        grouped
            .entry(line.key.clone())
            .or_insert_with(Vec::new)
            .push(line);
    }
    grouped
}

